// Task 2: Score Tracker

let totalScore = 0;
console.log("Starting score:", totalScore);

totalScore += 45;
console.log("After first test (+45):", totalScore);   // 45

totalScore += 30;
console.log("After second test (+30):", totalScore);  // 75

totalScore -= 5;
console.log("After deduction (-5):", totalScore);     // 70

totalScore *= 2;
console.log("After bonus round (x2):", totalScore);   // 140

totalScore++;
console.log("After increment (+1):", totalScore);     // 141

console.log("Remainder when divided by 7:", totalScore % 7); // 1